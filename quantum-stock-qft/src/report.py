def _build_table(rows: list[dict]) -> str:
    if not rows:
        return "<p><em>No data.</em></p>"
    headers = list(rows[0].keys())
    lines = ["<table>", "<tr>" + "".join(f"<th>{h}</th>" for h in headers) + "</tr>"]
    for row in rows:
        lines.append("<tr>" + "".join(f"<td>{row.get(h, '')}</td>" for h in headers) + "</tr>")
    lines.append("</table>")
    return "\n".join(lines)


def _fig_html(fig: Optional[plt.Figure], caption: str = "") -> str:
    if fig is None:
        return ""
    b64 = _fig_to_b64(fig)
    cap = f"<p><em>{caption}</em></p>" if caption else ""
    return f'<img src="data:image/png;base64,{b64}" alt="{caption}"/>{cap}'


# ─────────────────────────────────────────────────────────────────────────────
# Markdown report
# ─────────────────────────────────────────────────────────────────────────────

def _generate_markdown(interp: InterpretationReport) -> str:
    lines = [
        f"# Quantum Fourier Analysis of {interp.ticker} — Research Report",
        "",
        "## 1. Research Hypothesis",
        "",
        interp.hypothesis,
        "",
        "## 2. Data",
        "",
        interp.data_summary,
        "",
        "## 3. Preprocessing",
        "",
        interp.preprocessing_summary,
        "",
        "## 4. Classical FFT",
        "",
        interp.classical_summary,
        "",
        "## 5. QFT Results",
        "",
        interp.qft_summary,
        "",
        "## 6. Dominant Bins (Classical)",
        "",
    ]
    for row in interp.dominant_bins_classical:
        lines.append(f"- Bin {row['bin']}: f={row['frequency']:.5f}, "
                     f"period={row['period']}, power={row['power']:.5f}, "
                     f"DC={row['is_dc']}, neg_freq={row['is_negative_freq']}")
    lines += [
        "",
        "## 7. Spectral Agreement",
        "",
        interp.comparison_summary,
        "",
        "## 8. Limitations",
        "",
        interp.limitations,
        "",
        "## 9. Conclusion",
        "",
        interp.conclusion,
        "",
        "---",
        "*For educational and research purposes only. Not financial advice.*",
    ]
    return "\n".join(lines)


# ─────────────────────────────────────────────────────────────────────────────
# Public entry point
# ─────────────────────────────────────────────────────────────────────────────

def generate_report(
    interp: InterpretationReport,
    figures: Optional[dict[str, Optional[plt.Figure]]] = None,
    output_path: Optional[str] = None,
    fmt: str = "html",
) -> Path:
    """
    Write a self-contained report to disk.

    Parameters
    ----------
    interp      : InterpretationReport from interpretation.build_interpretation().
    figures     : Dict of named Matplotlib figures (keys: prices, preprocessed,
                  amplitude, spectra, diff).  None → omit images.
    output_path : Full file path.  None → outputs/{ticker}_report.{ext}
    fmt         : "html" or "markdown"

    Returns
    -------
    Path to the written file.
    """
    figs = figures or {}
    ext = "html" if fmt == "html" else "md"

    if output_path is None:
        Path("outputs").mkdir(parents=True, exist_ok=True)
        output_path = f"outputs/{interp.ticker}_report.{ext}"

    out = Path(output_path)
    out.parent.mkdir(parents=True, exist_ok=True)

    if fmt == "markdown":
        content = _generate_markdown(interp)
        out.write_text(content, encoding="utf-8")
        return out

    # HTML
    agree_class = (
        "ok"
        if interp.max_agreement_error < 1e-3
        else "warning"
    )
    content = _HTML_TEMPLATE.format(
        ticker=interp.ticker,
        hypothesis=interp.hypothesis,
        data_summary=interp.data_summary,
        preprocessing_summary=interp.preprocessing_summary,
        classical_summary=interp.classical_summary,
        qft_summary=interp.qft_summary,
        comparison_summary=interp.comparison_summary,
        limitations=interp.limitations,
        conclusion=interp.conclusion,
        table_classical=_build_table(interp.dominant_bins_classical),
        agreement_class=agree_class,
        fig_prices=_fig_html(figs.get("prices"), "Historical prices and daily returns"),
        fig_preprocessed=_fig_html(figs.get("preprocessed"), "Input signal after preprocessing"),
        fig_amplitude=_fig_html(figs.get("amplitude"), "L2-normalised amplitude vector ψ"),
        fig_spectra=_fig_html(figs.get("spectra"), "Power spectra: classical vs. QFT"),
        fig_diff=_fig_html(figs.get("diff"), "Absolute deviation |P_QFT - P_classical|"),
    )
    out.write_text(content, encoding="utf-8")
    return out
