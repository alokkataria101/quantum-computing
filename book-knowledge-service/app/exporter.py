"""app/exporter.py – export extracted questions to HTML, JSON, CSV, PDF."""

from __future__ import annotations

import csv
import io
import json
import logging
from pathlib import Path
from typing import Optional

from .models import QuestionRecord, ChapterRecord, ExportFormat

logger = logging.getLogger(__name__)

try:
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.styles import getSampleStyleSheet
    from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer
    REPORTLAB_AVAILABLE = True
except ImportError:
    REPORTLAB_AVAILABLE = False


# ─────────────────────────────────────────────────────────────────────────────
# JSON
# ─────────────────────────────────────────────────────────────────────────────

def to_json(questions: list[QuestionRecord], include_solutions: bool = True) -> bytes:
    records = []
    for q in questions:
        d = q.model_dump()
        if not include_solutions:
            d.pop("solution_text", None)
            d.pop("answer_text", None)
        records.append(d)
    return json.dumps(records, indent=2, default=str).encode()


# ─────────────────────────────────────────────────────────────────────────────
# CSV
# ─────────────────────────────────────────────────────────────────────────────

def to_csv(questions: list[QuestionRecord], include_solutions: bool = True) -> bytes:
    buf = io.StringIO()
    fields = [
        "question_id", "chapter_number", "question_type", "question_number",
        "question_text", "page_start", "page_end", "confidence",
    ]
    if include_solutions:
        fields += ["solution_text", "answer_text"]

    writer = csv.DictWriter(buf, fieldnames=fields, extrasaction="ignore")
    writer.writeheader()
    for q in questions:
        writer.writerow(q.model_dump())
    return buf.getvalue().encode()


# ─────────────────────────────────────────────────────────────────────────────
# HTML
# ─────────────────────────────────────────────────────────────────────────────

_HTML_HEAD = """<!DOCTYPE html>
<html lang="en"><head><meta charset="utf-8"/>
<title>Question Export</title>
<style>
body{font-family:system-ui,sans-serif;max-width:900px;margin:40px auto;padding:0 20px;line-height:1.6}
h1,h2{color:#0f3460} .q-block{border:1px solid #e5e7eb;border-radius:6px;padding:14px 18px;margin:14px 0}
.q-type{font-size:.78em;background:#dce6f7;border-radius:10px;padding:2px 8px;margin-right:6px}
.solution{background:#f7f8fa;border-left:3px solid #28a745;padding:8px 12px;margin-top:8px}
.answer{background:#fff8e1;border-left:3px solid #f0ad4e;padding:8px 12px;margin-top:4px}
.meta{font-size:.78em;color:#57606a;margin-top:6px}
</style></head><body>
"""


def to_html(
    questions: list[QuestionRecord],
    chapters: list[ChapterRecord],
    book_title: str = "Book",
    include_solutions: bool = True,
) -> bytes:
    ch_map = {c.chapter_id: c for c in chapters}
    lines = [_HTML_HEAD, f"<h1>{book_title} — Extracted Questions</h1>"]

    current_ch: Optional[str] = None
    for q in questions:
        if q.chapter_id != current_ch:
            ch = ch_map.get(q.chapter_id)
            title = ch.title if ch else q.chapter_id
            lines.append(f"<h2>Chapter {q.chapter_number}: {title}</h2>")
            current_ch = q.chapter_id

        num_label = f"#{q.question_number}" if q.question_number else ""
        lines.append(
            f'<div class="q-block">'
            f'<span class="q-type">{q.question_type.value}</span>'
            f'<strong>{num_label}</strong> '
            f'<span>{q.question_text}</span>'
        )
        if include_solutions and q.solution_text:
            lines.append(f'<div class="solution"><strong>Solution:</strong> {q.solution_text}</div>')
        if include_solutions and q.answer_text:
            lines.append(f'<div class="answer"><strong>Answer:</strong> {q.answer_text}</div>')
        lines.append(
            f'<div class="meta">Pages {q.page_start}–{q.page_end} | '
            f'Confidence {q.confidence:.0%}</div></div>'
        )

    lines.append('<footer style="margin-top:3em;border-top:1px solid #e5e7eb;'
                 'padding-top:8px;font-size:.78em;color:#57606a;text-align:center">'
                 'Generated by book-knowledge-service</footer></body></html>')
    return "\n".join(lines).encode()


# ─────────────────────────────────────────────────────────────────────────────
# PDF (ReportLab)
# ─────────────────────────────────────────────────────────────────────────────

def to_pdf(
    questions: list[QuestionRecord],
    chapters: list[ChapterRecord],
    book_title: str = "Book",
    include_solutions: bool = True,
) -> bytes:
    if not REPORTLAB_AVAILABLE:
        raise RuntimeError("reportlab is not installed. Install it with: pip install reportlab")

    buf = io.BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=A4, title=book_title)
    styles = getSampleStyleSheet()
    story = [Paragraph(f"{book_title} — Extracted Questions", styles["Title"]), Spacer(1, 20)]

    ch_map = {c.chapter_id: c for c in chapters}
    current_ch: Optional[str] = None

    for q in questions:
        if q.chapter_id != current_ch:
            ch = ch_map.get(q.chapter_id)
            title = ch.title if ch else q.chapter_id
            story.append(Paragraph(f"Chapter {q.chapter_number}: {title}", styles["Heading2"]))
            current_ch = q.chapter_id

        num = f"[{q.question_number}] " if q.question_number else ""
        story.append(Paragraph(
            f"<b>{q.question_type.value} {num}</b> {q.question_text}",
            styles["Normal"],
        ))
        if include_solutions and q.solution_text:
            story.append(Paragraph(f"<i>Solution:</i> {q.solution_text}", styles["Normal"]))
        if include_solutions and q.answer_text:
            story.append(Paragraph(f"<i>Answer:</i> {q.answer_text}", styles["Normal"]))
        story.append(Spacer(1, 6))

    doc.build(story)
    return buf.getvalue()


# ─────────────────────────────────────────────────────────────────────────────
# Dispatcher
# ─────────────────────────────────────────────────────────────────────────────

def export(
    fmt: ExportFormat,
    questions: list[QuestionRecord],
    chapters: list[ChapterRecord],
    book_title: str = "Book",
    include_solutions: bool = True,
) -> tuple[bytes, str]:
    """
    Returns (content_bytes, media_type).
    """
    if fmt == ExportFormat.json:
        return to_json(questions, include_solutions), "application/json"
    if fmt == ExportFormat.csv:
        return to_csv(questions, include_solutions), "text/csv"
    if fmt == ExportFormat.html:
        return to_html(questions, chapters, book_title, include_solutions), "text/html"
    if fmt == ExportFormat.pdf:
        return to_pdf(questions, chapters, book_title, include_solutions), "application/pdf"
    raise ValueError(f"Unknown export format: {fmt}")
